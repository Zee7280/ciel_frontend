/** Custom sentinel only. Named options such as "Other Essential Resource Support" are complete choices. */
export function isOtherTaxonomyChoice(value?: string): boolean {
    const text = String(value || '').trim();
    if (!text) return false;
    if (/^other$/i.test(text)) return true;
    if (/other\s*\/\s*custom/i.test(text)) return true;
    if (/^other…$|^other\.\.\.$/i.test(text)) return true;
    return false;
}
