export function financialReadiness(opts: { price?: number; unitCost?: number; budgetLines?: { amount?: number }[]; cashOnHand?: number; monthlyCosts?: number; finAssumptions?: string }) {
    let n = 0;
    if ((opts.price || 0) > 0) n += 20;
    if ((opts.unitCost || 0) > 0) n += 20;
    if ((opts.budgetLines || []).some((r) => (r.amount || 0) > 0)) n += 25;
    if ((opts.cashOnHand || 0) > 0 || (opts.monthlyCosts || 0) > 0) n += 20;
    if (opts.finAssumptions) n += 15;
    if (n >= 70) return "Ready";
    if (n >= 40) return "Developing";
    if (n > 0) return "Started";
    return "Not started";
}

export function teamHealthLabel(opts: { paceScore?: string; burnoutSigns?: string[]; burnoutPlan?: string }) {
    const signs = (opts.burnoutSigns || []).filter((s) => s && s !== "None of these");
    const pace = Number(opts.paceScore || 0);
    if (!pace && !signs.length && !opts.burnoutPlan) return "Not assessed";
    if (pace <= 2 || signs.length >= 3) return "At risk";
    if (opts.burnoutPlan || pace >= 4) return "Healthy plan";
    return "Watch";
}

